// Builds the W4W game page served by /api/w4w/play (only to people let in).
// Source: w4w/game.html (the same file as the artifact prototype) + w4w/site-shim.js.
// Run from apps/web: node w4w/build.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
let game = fs.readFileSync(path.join(root, 'w4w/game.html'), 'utf8')
const shim = fs.readFileSync(path.join(root, 'w4w/site-shim.js'), 'utf8')

const swap = (from, to) => {
  if (!game.includes(from)) throw new Error(`w4w-build: not found: ${from.slice(0, 60)}`)
  game = game.replace(from, to)
}
// the site serves the model as a real .glb, no base64 detour
swap(
  "fetch('kit.txt').then(r => { if (!r.ok) throw new Error('kit.txt ' + r.status); return r.text(); })\n  .then(b64 => { const s = atob(b64.trim()), bin = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) bin[i] = s.charCodeAt(i);\n    return new Promise((res, rej) => new GLTFLoader().parse(bin.buffer, '', res, rej)); })",
  "fetch('kit.glb').then(r => { if (!r.ok) throw new Error('kit.glb ' + r.status); return r.arrayBuffer(); })\n  .then(buf => new Promise((res, rej) => new GLTFLoader().parse(buf, '', res, rej)))",
)
swap('PROTOTYPE · NO RIG IS REALLY RENTED</div>', 'CLOSED TEST · NO RIG IS REALLY RENTED</div>')

const html = `<!doctype html>
<html lang="en"><head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="robots" content="noindex">
<base href="/w4w-assets/">
<title>W4W · Aigarth</title>
<script>${shim}</script>
</head><body>
${game}
</body></html>
`
const out = `// Generated by w4w/build.mjs from w4w/game.html. Do not edit by hand.\nexport const GAME_HTML: string = ${JSON.stringify(html)}\n`
fs.writeFileSync(path.join(root, 'src/lib/w4w/game-html.ts'), out)
console.log(`w4w-build: ${(html.length / 1024).toFixed(0)} KB`)
